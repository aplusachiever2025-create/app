create or replace function public.set_match_case_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists match_cases_updated_at on public.match_cases;
create trigger match_cases_updated_at before update on public.match_cases
for each row execute function public.set_match_case_updated_at();

create or replace function public.validate_match_interest()
returns trigger language plpgsql security definer set search_path = public
as $
begin
  if not exists (
    select 1 from public.parent_requests
    where id = new.parent_request_id and request_status = 'active'
  ) then
    raise exception 'parent request is not active';
  end if;

  if not exists (
    select 1 from public.tutor_profiles
    where id = new.tutor_id and tutor_status = 'active'
  ) then
    raise exception 'tutor profile is not active';
  end if;

  return new;
end;
$;

drop trigger if exists validate_match_interest on public.match_interests;
create trigger validate_match_interest before insert on public.match_interests
for each row execute function public.validate_match_interest();

create or replace function public.register_match_interest()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.match_cases(parent_request_id, tutor_id, status, parent_interested_at, tutor_interested_at)
  values(
    new.parent_request_id,
    new.tutor_id,
    'new',
    case when new.interested_by = 'parent' then new.created_at else null end,
    case when new.interested_by = 'tutor' then new.created_at else null end
  )
  on conflict(parent_request_id, tutor_id) do update set
    parent_interested_at = coalesce(public.match_cases.parent_interested_at, excluded.parent_interested_at),
    tutor_interested_at = coalesce(public.match_cases.tutor_interested_at, excluded.tutor_interested_at),
    status = case
      when coalesce(public.match_cases.parent_interested_at, excluded.parent_interested_at) is not null
       and coalesce(public.match_cases.tutor_interested_at, excluded.tutor_interested_at) is not null
      then 'both_interested'
      else public.match_cases.status
    end;
  return new;
end;
$$;

drop trigger if exists match_interest_to_case on public.match_interests;
create trigger match_interest_to_case after insert on public.match_interests
for each row execute function public.register_match_interest();

