create table if not exists public.match_interests (
  id bigint generated by default as identity primary key,
  parent_request_id bigint not null references public.parent_requests(id) on delete cascade,
  tutor_id bigint not null references public.tutor_profiles(id) on delete cascade,
  interested_by text not null check (interested_by in ('parent','tutor')),
  created_at timestamptz not null default now(),
  unique(parent_request_id, tutor_id, interested_by)
);

create table if not exists public.match_cases (
  id bigint generated by default as identity primary key,
  parent_request_id bigint not null references public.parent_requests(id) on delete cascade,
  tutor_id bigint not null references public.tutor_profiles(id) on delete cascade,
  status text not null default 'new' check (status in ('new','both_interested','contacting','trial','confirmed','not_concluded','cancelled')),
  parent_interested_at timestamptz,
  tutor_interested_at timestamptz,
  last_contacted_at timestamptz,
  confirmed_at timestamptz,
  confirmed_by uuid references auth.users(id),
  not_concluded_reason text,
  not_concluded_note text,
  hourly_rate numeric(10,2),
  lesson_duration_hours numeric(4,2),
  lessons_per_week numeric(4,2),
  first_lesson_date date,
  commission_amount numeric(10,2),
  commission_status text not null default 'pending' check (commission_status in ('pending','invoiced','paid','waived','cancelled')),
  platform_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(parent_request_id, tutor_id)
);

